"""Vocabulary helpers: map token ids to the raw bytes they stand for.

Qwen uses byte-level BPE: every byte 0..255 is written in vocab.json as one
printable unicode character (space is ``Ġ``, newline is ``Ċ``, the two
bytes of ``é`` are ``Ã©``). Turning a token back into text therefore means
undoing that table and decoding UTF-8, not just replacing ``Ġ``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

PLACEHOLDER = "Ā"
"""Stands in for a character whose UTF-8 bytes are not all generated yet."""


def bytes_to_unicode() -> dict[int, str]:
    """Map each byte to the character byte-level BPE uses for it.

    Returns:
        Mapping from byte value 0..255 to a single character.
    """
    ordered = (
        list(range(ord("!"), ord("~") + 1))
        + list(range(ord("¡"), ord("¬") + 1))
        + list(range(ord("®"), ord("ÿ") + 1))
    )
    chars = ordered[:]
    extra = 0
    for byte in range(256):
        if byte not in ordered:
            ordered.append(byte)
            chars.append(256 + extra)
            extra += 1
    return {byte: chr(code) for byte, code in zip(ordered, chars)}


def load_vocab(path: str | Path) -> dict[str, int]:
    """Load a Hugging Face vocab.json file.

    Args:
        path: Path returned by ``get_path_to_vocab_file()``.

    Returns:
        Mapping from raw token string to token id.
    """
    try:
        with Path(path).open("r", encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError) as exc:
        print(f"Error: cannot load vocab from {path}: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
    if not isinstance(data, dict):
        print(f"Error: unexpected vocab format in {path}", file=sys.stderr)
        raise SystemExit(1)
    return data


def token_to_bytes(raw_token: str, byte_decoder: dict[str, int]) -> bytes:
    """Convert a vocab.json token into the bytes it contributes.

    Args:
        raw_token: Token string as stored in vocab.json.
        byte_decoder: Inverse of :func:`bytes_to_unicode`.

    Returns:
        Raw bytes (possibly an incomplete UTF-8 sequence).
    """
    data = bytearray()
    for char in raw_token:
        byte = byte_decoder.get(char)
        if byte is None:
            data.extend(char.encode("utf-8"))
        else:
            data.append(byte)
    return bytes(data)


def build_id_to_bytes(vocab: dict[str, int]) -> dict[int, bytes]:
    """Build the token-id → bytes mapping for the whole vocabulary.

    Args:
        vocab: Raw vocab mapping token → id.

    Returns:
        Mapping id → bytes.
    """
    byte_decoder = {char: byte for byte, char in bytes_to_unicode().items()}
    return {
        token_id: token_to_bytes(token, byte_decoder)
        for token, token_id in vocab.items()
    }


def decode_prefix(data: bytes) -> tuple[str, bool] | None:
    """Decode generated bytes that may end in the middle of a character.

    Args:
        data: UTF-8 bytes generated so far.

    Returns:
        ``(text, pending)`` where ``pending`` says that the last character is
        still incomplete (it is left out of ``text``), or None when the bytes
        can never become valid UTF-8.
    """
    try:
        return data.decode("utf-8"), False
    except UnicodeDecodeError as exc:
        if exc.reason != "unexpected end of data":
            return None
        return data[: exc.start].decode("utf-8"), True
